void handleRestore(BuildContext context) async {
  // 1. Let the user pick a file
  final result = await FilePicker.platform.pickFiles(
    type: FileType.custom,
    allowedExtensions: ['mdb'],
  );

  // 2. Check if the user cancelled the picker
  if (result == null || result.files.single.path == null) {
    print_log("File picking cancelled by user.");
    return;
  }

  // 3. Get the path of the selected file
  final backupPath = result.files.single.path!;
  print_log("Selected backup file: $backupPath");

  final store_path = AppConstants.objectbox_path;

  // 4. Proceed with the restore operation
  bool success = await restoreDatabase(context, backupPath);

  if (success) {
    print_log("Restore successful! UI should refresh.");
    screen_massage(context, "Restore successful! Please restart the app.");
  }
}












