  }

  /// Create a Backup
  Future<String?> backupDatabase(BuildContext context, String backupPath) async {
    // 1. Get the Service (Not just the store, get the Service so we can update it later)
    final objectBoxService = Provider.of<ObjectBoxService>(context, listen: false);
    Store store = objectBoxService.store;

    try {
      // CRITICAL FIX: Capture path BEFORE closing the store
      final dbDirectoryPath = store.directoryPath;

      // 2. Close the store
      store.close();

      // 3. File Operations
      final srcFile = File(p.join(dbDirectoryPath, 'data.mdb'));
      if (!srcFile.existsSync()) {
        // Re-open if file missing (recovery)
        store = await openStore(directory: dbDirectoryPath);
        objectBoxService.store = store; // Update Provider
        return null;
      }

      final backupFile = File(backupPath);
      if (!await backupFile.parent.exists()) {
        await backupFile.parent.create(recursive: true);
      }

      await srcFile.copy(backupPath);

      // 4. Re-open the store
      store = await openStore(directory: dbDirectoryPath);
      
      // CRITICAL: Update the Provider with the new open store instance
      objectBoxService.store = store; 
      // If ObjectBoxService extends ChangeNotifier, call notifyListeners() inside it.

      return backupPath;
    } catch (e) {
      // print_log_red("Backup failed: $e");
      // print("Backup failed: $e");
      screen_massage(context, "Backup failed: $e");
      return null;
    }
  }

  /// Restore from Backup
  /// [backupFilePath] is the full path to your .mdb backup file
  Future<bool> restoreDatabase(BuildContext context, String backupFilePath) async {
    // 1. Get Service
    final objectBoxService = Provider.of<ObjectBoxService>(context, listen: false);
    Store store = objectBoxService.store;

    try {
      final backupFile = File(backupFilePath);
      if (!await backupFile.exists()) return false;

      // CRITICAL FIX: Capture path BEFORE closing
      final dbDirectoryPath = store.directoryPath;

      // 2. Close store
      store.close();

      // 3. Overwrite file
      final currentDbFile = File(p.join(dbDirectoryPath, 'data.mdb'));
      
      // Delete lock file if exists
      final lockFile = File(p.join(dbDirectoryPath, 'lock.mdb'));
      if (await lockFile.exists()) {
        await lockFile.delete();
      }

      await backupFile.copy(currentDbFile.path);

      // 4. Re-open store
      store = await openStore(directory: dbDirectoryPath);

      // CRITICAL: Update the Provider
      objectBoxService.store = store;

      return true;
    } catch (e) {
      // Recovery
      // store = await openStore(directory: ...);
      // objectBoxService.store = store;
      // print("Restore failed: $e");
      screen_massage(context, "Restore failed: $e");
      return false;
    }
  }



